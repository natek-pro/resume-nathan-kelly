import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const local = createRequire(import.meta.url);
let marked;
try { ({ marked } = local('marked')); }
catch (error) {
  if (error.code !== 'MODULE_NOT_FOUND') throw error;
  const bundled = createRequire(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json'));
  ({ marked } = bundled('marked'));
}

export const fingerprint = text => createHash('sha256').update(text).digest('hex');
const label = text => text.includes(' — ') ? text.slice(0, text.lastIndexOf(' — ')) : text;

export function collectBullets(markdown, config) {
  const codes = new Set();
  for (const role of config.roles) {
    if (!/^[A-Z0-9]+-[A-Z0-9]+$/.test(role.code) || codes.has(role.code)) throw new Error(`Invalid or duplicate role code: ${role.code}`);
    codes.add(role.code);
    if (config.roles.filter(r => r.organization === role.organization && r.role === role.role).length !== 1) throw new Error(`Ambiguous role mapping: ${role.code}`);
    const validateTags = tags => {
      if (!Array.isArray(tags) || tags.length < 3 || new Set(tags).size !== tags.length || tags.some(tag => !Object.hasOwn(config.tags, tag))) throw new Error(`Use at least three unique registered tags for ${role.code}.`);
      if (!tags.some(tag => config.tags[tag].kind === 'target')) throw new Error(`Missing target-role tag for ${role.code}.`);
    };
    validateTags(role.defaultTags);
    for (const [hash, tags] of Object.entries(role.bullets)) {
      if (!/^[a-f0-9]{64}$/.test(hash)) throw new Error(`Invalid bullet fingerprint for ${role.code}.`);
      validateTags(tags);
    }
  }
  const groups = [];
  let inExperience = false;
  let organization = '';
  let current;
  for (const token of marked.lexer(markdown)) {
    if (token.type === 'heading') {
      if (token.depth === 2) {
        inExperience = token.text === 'Professional Experience';
        organization = '';
        current = undefined;
      } else if (inExperience && token.depth === 3) {
        organization = label(token.text);
        current = undefined;
      } else if (inExperience && token.depth === 4) {
        const roleName = label(token.text);
        const mapping = config.roles.find(role => role.organization === organization && role.role === roleName);
        if (!mapping) throw new Error(`Register organization/role in config/bullet-tags.json: ${organization} / ${roleName}`);
        if (groups.some(group => group.code === mapping.code)) throw new Error(`Repeated role: ${mapping.code}`);
        current = { code: mapping.code, organization, heading: token.text, context: '', bullets: [], mapping };
        groups.push(current);
      }
    } else if (inExperience && token.type === 'list') {
      if (!current || token.ordered) throw new Error('Experience bullets must be unordered lists beneath a registered role.');
      for (const item of token.items) {
        if (item.task || item.tokens.some(child => child.type === 'list')) throw new Error('Task/nested bullets require an explicit catalog parser update.');
        const text = item.text.trimEnd();
        const hash = fingerprint(text);
        const tags = current.mapping.bullets[hash];
        current.bullets.push({
          id: `${current.code}-${String(current.bullets.length).padStart(2, '0')}`,
          text, hash, tags: tags || current.mapping.defaultTags,
          reviewed: Boolean(tags),
        });
      }
    } else if (current && !current.bullets.length && token.type === 'paragraph' && /^\*[^*].*\*$/s.test(token.text)) {
      current.context = token.text;
    }
  }
  if (!groups.length) throw new Error('No experience roles found.');
  return groups;
}

export function renderCatalog(markdown, config) {
  const groups = collectBullets(markdown, config);
  const all = groups.flatMap(group => group.bullets);
  const pending = all.filter(bullet => !bullet.reviewed);
  const lines = [
    '# Resume bullet catalog', '',
    '<!-- Generated by scripts/generate-bullet-catalog.mjs. Do not edit. -->', '',
    `Source: \`resume_source.md\` · SHA-256: \`${fingerprint(markdown)}\``, '',
    `${all.length} bullets across ${groups.length} roles. Tag review pending: **${pending.length}**.`, '',
    'This catalog contains Professional Experience list bullets only. Role descriptions, the patent block, summary, competencies, education, and skills remain in the master source and may also matter when selecting a resume subset.', '',
    'Identifiers use company-role-zero-based-index (e.g. `TPT-HPT-02` is the third bullet under Head of Product & Technology). Indexes reset for each role and change after insertion, removal, or reordering. Pair selections with the source hash; reread text before reusing an older selection. Bullet fingerprints bind reviewed tags to exact Markdown text, so tags follow unchanged bullets when reordered.', '',
    'Tags are editorial selection aids, not additional resume claims or automatic job-fit scores. `target` tags name possible application directions; `capability` tags describe evidence in the bullet. Read the text and surrounding role before choosing. Pending entries show broad role defaults only and require an agent to review their tags.', '',
    'Rebuild: `npm run catalog`. Check freshness: `npm run check:catalog`. Require all tags reviewed: `npm run check:catalog -- --require-reviewed`. See `AGENTS.md` and `docs/generator.md` for maintenance instructions.', '',
    '## Role identifiers', '',
    '| Prefix | Organization | Role | Bullets |',
    '| --- | --- | --- | --- |',
    ...groups.map(group => `| \`${group.code}\` | ${group.organization} | ${label(group.heading)} | ${group.bullets.length} |`), '',
    '## Tag vocabulary', '',
    '| Tag | Kind | Meaning |', '| --- | --- | --- |',
    ...Object.entries(config.tags).map(([tag, definition]) => `| \`${tag}\` | ${definition.kind} | ${definition.description} |`), '',
  ];
  for (const group of groups) {
    lines.push(`## ${group.code} — ${group.organization}`, '', group.heading, '');
    if (group.context) lines.push(group.context, '');
    for (const bullet of group.bullets) {
      lines.push(`### ${bullet.id}`, '', bullet.text, '',
        `Tags: ${bullet.tags.map(tag => `\`${tag}\``).join(' · ')}`, '',
        `Tag review: **${bullet.reviewed ? 'reviewed' : 'pending — role defaults only'}** · Bullet SHA-256: \`${bullet.hash}\``, '');
    }
  }
  return { content: lines.join('\n'), pending };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const markdown = await fs.readFile(path.join(root, 'resume_source.md'), 'utf8');
  const config = JSON.parse(await fs.readFile(path.join(root, 'config/bullet-tags.json'), 'utf8'));
  const { content, pending } = renderCatalog(markdown, config);
  const target = path.join(root, 'docs/bullet-catalog.md');
  if (process.argv.includes('--check')) {
    const current = await fs.readFile(target, 'utf8').catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (current !== content) throw new Error('Bullet catalog is stale. Run npm run catalog.');
    console.log('PASS: Bullet catalog matches source and tag configuration.');
  } else {
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, content);
    console.log('Generated docs/bullet-catalog.md.');
  }
  if (pending.length) {
    console.log(`Tag review needed: ${pending.map(bullet => bullet.id).join(', ')}`);
    if (process.argv.includes('--require-reviewed')) process.exitCode = 1;
  }
}
